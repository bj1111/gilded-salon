"""Copy math outputs into the web-sdk app: game config plus real books for Storybook.

Books are sampled with the published lookup-table weights, so the "random" story plays
rounds at the same odds a real player would get.

    python games/sticky_fruits/export_frontend.py
"""

import csv
import io
import json
import os
import re

import numpy as np
import zstandard

GAME_DIR = os.path.dirname(os.path.abspath(__file__))
LIBRARY = os.path.join(GAME_DIR, "library")
APP_DIR = os.path.abspath(os.path.join(GAME_DIR, "..", "..", "..", "web-sdk", "apps", "sticky_fruits"))

NUM_BASE_BOOKS = 400
NUM_BONUS_BOOKS = 60
NUM_MODE_BOOKS = 40  # per bought / Bonus Hunt mode, for the integrity story
NUM_HUNT_BONUS_BOOKS = 6
SEED = 20261002


def load_books(mode="base"):
    books = {}
    path = os.path.join(LIBRARY, "publish_files", f"books_{mode}.jsonl.zst")
    with open(path, "rb") as f:
        for line in io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(f), encoding="utf-8"):
            book = json.loads(line)
            books[book["id"]] = book
    return books


def load_weights(mode="base"):
    ids, weights = [], []
    with open(os.path.join(LIBRARY, "publish_files", f"lookUpTable_{mode}_0.csv"), encoding="UTF-8") as f:
        for row in csv.reader(f):
            ids.append(int(row[0]))
            weights.append(int(row[1]))
    w = np.array(weights, dtype=float)
    return np.array(ids), w / w.sum()


def write_ts(path, header, data):
    with open(path, "w", encoding="UTF-8") as f:
        f.write(header)
        f.write("export default ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {os.path.relpath(path, APP_DIR)} ({os.path.getsize(path) / 1e6:.1f} MB)")


ID_RE = re.compile(r'^\{"id": (\d+)')
CRITERIA_RE = re.compile(r'"criteria": "([^"]+)"')


def stream_lines(mode):
    """(id, raw line) for every book of a mode, without parsing the JSON."""
    path = os.path.join(LIBRARY, "publish_files", f"books_{mode}.jsonl.zst")
    with open(path, "rb") as f:
        for line in io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(f), encoding="utf-8"):
            yield int(ID_RE.match(line).group(1)), line


def write_mode_samples(mode, rng, data_dir, generated):
    """NUM_MODE_BOOKS books of a mode at its published odds. Bonus Hunt also gets a few of its
    free-spin rounds (about 1 in 51 at natural odds, so a plain sample rarely holds one).
    Streams the books and parses only the sampled ones (super books run to gigabytes of JSON)."""
    mode_ids, mode_probs = load_weights(mode)
    picked_ids = [int(i) for i in rng.choice(mode_ids, size=NUM_MODE_BOOKS, p=mode_probs)]
    if mode == "hunt":
        criteria = {book_id: CRITERIA_RE.search(line[-200:]).group(1) for book_id, line in stream_lines(mode)}
        free = np.array([criteria[int(i)] == "freegame" for i in mode_ids])
        free_ids = rng.choice(mode_ids[free], size=NUM_HUNT_BONUS_BOOKS, p=mode_probs[free] / mode_probs[free].sum())
        picked_ids += [int(i) for i in free_ids]
    wanted = set(picked_ids)
    found = {book_id: json.loads(line) for book_id, line in stream_lines(mode) if book_id in wanted}
    write_ts(os.path.join(data_dir, f"{mode}_mode_books.ts"), generated, [found[i] for i in picked_ids])


def main():
    assert os.path.isdir(APP_DIR), f"web-sdk app not found at {APP_DIR}"
    generated = "// Generated by math-sdk/games/sticky_fruits/export_frontend.py. Do not edit.\n"

    config = json.load(open(os.path.join(LIBRARY, "configs", "config_fe_sticky_fruits.json"), encoding="UTF-8"))
    symbols = {}
    for entry in config["symbols"]:
        symbols.update(entry)
    config["symbols"] = dict(sorted(symbols.items()))
    config["providerName"] = "sticky_fruits"
    config["gameName"] = "Sticky Fruits"
    config_path = os.path.join(APP_DIR, "src", "game", "config.ts")
    with open(config_path, "w", encoding="UTF-8") as f:
        f.write(generated)
        f.write("const config = ")
        json.dump(config, f, separators=(",", ":"))
        f.write(";\n\n")
        # JSON infers padding symbol names as `string`; narrow them to the real symbol names
        f.write("type SymbolName = keyof typeof config.symbols;\n")
        f.write("export default config as Omit<typeof config, 'paddingReels'> & {\n")
        f.write("\tpaddingReels: Record<keyof typeof config.paddingReels, { name: SymbolName }[][]>;\n")
        f.write("};\n")
    print(f"wrote {os.path.relpath(config_path, APP_DIR)}")

    books = load_books()
    ids, probs = load_weights()
    rng = np.random.default_rng(SEED)
    data_dir = os.path.join(APP_DIR, "src", "stories", "data")

    base_ids = rng.choice(ids, size=NUM_BASE_BOOKS, p=probs)
    write_ts(os.path.join(data_dir, "base_books.ts"), generated, [books[int(i)] for i in base_ids])

    free_mask = np.array([books[int(i)]["criteria"] == "freegame" for i in ids])
    bonus_ids = rng.choice(ids[free_mask], size=NUM_BONUS_BOOKS, p=probs[free_mask] / probs[free_mask].sum())
    write_ts(os.path.join(data_dir, "bonus_books.ts"), generated, [books[int(i)] for i in bonus_ids])

    maxwin = next(b for b in books.values() if b["criteria"] == "wincap")
    write_ts(os.path.join(data_dir, "maxwin_books.ts"), generated, [maxwin])

    # bought modes and Bonus Hunt, sampled at their published odds
    for mode in ("bonus", "super", "hunt"):
        write_mode_samples(mode, rng, data_dir, generated)

    picked = [books[int(i)] for i in base_ids]
    print(
        f"base sample: {sum(b['payoutMultiplier'] > 0 for b in picked)} wins, "
        f"{sum(b['criteria'] == 'freegame' for b in picked)} bonus rounds, "
        f"RTP {sum(b['payoutMultiplier'] for b in picked) / 100 / len(picked):.3f}"
    )


if __name__ == "__main__":
    main()
